/** Swatch colors for the preset picker UI (5 representative colors per mode). */
export function getPresetSwatchColors(
  presetId: ColorPresetId,
  mode: "light" | "dark"
): string[] {
  const preset = THEME_PRESETS[presetId];
  const vars = mode === "light" ? preset.light : preset.dark;

  if (Object.keys(vars).length === 0) {
    // Default preset: return index.css baseline colors
    return mode === "light"
      ? [
          "oklch(0.205 0 0)",
          "oklch(0.97 0 0)",
          "oklch(0.556 0 0)",
          "oklch(0.577 0.245 27.325)",
          "oklch(1 0 0)",
        ]
      : [
          "oklch(0.922 0 0)",
          "oklch(0.269 0 0)",
          "oklch(0.708 0 0)",
          "oklch(0.704 0.191 22.216)",
          "oklch(0.145 0 0)",
        ];
  }

  return [
    vars["primary"] ?? "",
    vars["secondary"] ?? "",
    vars["muted-foreground"] ?? "",
    vars["destructive"] ?? "",
    vars["background"] ?? "",
  ];
}
